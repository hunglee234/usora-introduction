// Run with: PLAYWRIGHT_MODULE=/absolute/path/to/playwright/index.mjs node scripts/navigation-check.mjs
import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch();
try {
  const context = await browser.newContext();
  const page = await context.newPage({ viewport: { width: 1440, height: 900 } });
  const origin = process.env.TEST_ORIGIN || 'http://127.0.0.1:4173';
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${origin}/policy-privacy`);
  await page.evaluate(() => { window.documentMarker = 'same-document'; window.headerMarker = document.querySelector('header'); });
  let requests = 0;
  page.on('request', () => requests++);
  await context.setOffline(true);
  const before = await page.evaluate(() => scrollY);
  await page.locator('.policy-tabs a[href="/policy-terms"]').click();
  assert(page.url().endsWith('/policy-terms'));
  assert.equal(await page.title(), 'Terms of Service · Usora');
  assert.equal(await page.locator('h1').textContent(), 'Our shared ground.');
  assert.equal(await page.evaluate(() => scrollY), before);
  assert.equal(await page.locator('link[rel="canonical"]').getAttribute('href'), 'https://usora.web.app/policy-terms');
  assert.equal(await page.locator('.policy-tabs a:focus').getAttribute('href'), '/policy-terms');
  await page.locator('.policy-tabs a[href="/policy-deletion"]').click();
  assert.equal(await page.locator('h1').textContent(), 'You’re in control.');
  await page.goBack();
  assert.equal(await page.locator('h1').textContent(), 'Our shared ground.');
  await page.goBack();
  assert.equal(await page.locator('h1').textContent(), 'Privacy, with care.');
  await page.goForward();
  assert.equal(await page.locator('h1').textContent(), 'Our shared ground.');
  assert.equal(await page.evaluate(() => window.documentMarker), 'same-document');
  assert(await page.evaluate(() => window.headerMarker === document.querySelector('header')));
  assert.equal(requests, 0, 'Switching tabs must not request another document or fetch data');
  await page.locator('.contents a[href="#purchases"]').click();
  assert(page.url().endsWith('#purchases'));
  await page.waitForTimeout(600);
  assert.equal(await page.locator('.contents a[aria-current="location"]').getAttribute('href'), '#purchases');
  await page.goBack();
  assert(page.url().endsWith('/policy-terms'));
  await page.evaluate(() => window.print = () => { window.printed = true; });
  await page.locator('[data-print]').click();
  assert(await page.evaluate(() => window.printed));
  await page.locator('.brand').click();
  assert.equal(new URL(page.url()).pathname, '/');
  await page.locator('.button').click();
  assert.equal(new URL(page.url()).pathname, '/policy-privacy');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.policy-tabs a[href="/policy-deletion"]').click();
  assert.equal(await page.evaluate(() => window.documentMarker), 'same-document');
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await context.setOffline(false);
  await page.reload();
  assert.equal(await page.locator('h1').textContent(), 'You’re in control.');
  const nojs = await browser.newContext({ javaScriptEnabled: false });
  const fallback = await nojs.newPage();
  await fallback.goto(`${origin}/policy-privacy`);
  await fallback.locator('.policy-tabs a[href="/policy-terms"]').click();
  assert.equal(await fallback.locator('h1').textContent(), 'Our shared ground.');
  assert.deepEqual(errors, []);
  console.log('PASS: same-document/offline tabs, URL + metadata + focus, scroll preservation, Back/Forward, anchors, print, home navigation, mobile, direct reload, and no-JS fallback.');
} finally { await browser.close(); }
